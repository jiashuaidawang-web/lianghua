//     不需要再反序列化成 DTO。
//
//   💡 System Prompt 的角色定位：
//     Day 2："分析师" → 分析股票，输出结构化 DTO
//     Day 5 Planner："规划师" → 拆任务，输出 List<Task>
//     Day 5 Render："财经助手" → 汇总结果，输出人话
