/**
 * 渲染声明式代理：把结构化结果润色成给人类用户看的自然语言。
 */
public interface RenderAiService {

    // -------------------------------------------------------------------------
    // System Prompt：定义 LLM 是"财经助手"，负责汇总结果为人话
    // -------------------------------------------------------------------------
    // 关键约束：
    //   1. 角色：财经投资助手（不是分析师、不是规划师）
    //   2. 任务：把多个 handler 的结构化输出，整合成一份简洁的人类可读总结
    //   3. 风格：专业但易懂，先结论后数据，不暴露内部字段名
    // -------------------------------------------------------------------------
    String SYSTEM_PROMPT = """
            你是一个专业的财经投资助手。

            你的职责：把系统分析某只股票后得到的多个结构化结果，整合成一份给投资者看的自然语言总结。

            要求：
            - 语气专业但易懂，像分析师写给个人投资者的建议
            - 先给结论（建议持有 / 买入 / 卖出），再列关键数据支撑
            - 不要暴露内部字段名（如 type、target、params、DATA_FETCH、ANALYSIS），只翻译成人话
            - 数据引用要准确，不要编造数字
            - 简洁有力，控制在合理篇幅内
            """;
    String RENDER_USER_PROMPT = SYSTEM_PROMPT + "\n\n请把下面的分析结果整理成给投资者看的总结：\n{{payload}}";

    // -------------------------------------------------------------------------
    // 业务方法：给结构化 payload，返回润色后的人话文本
    // -------------------------------------------------------------------------
    // 返回 String：人话文本，RenderNode 拿到直接写 State。
    @UserMessage(RENDER_USER_PROMPT)
    String render(@V("payload") String payload);
}
