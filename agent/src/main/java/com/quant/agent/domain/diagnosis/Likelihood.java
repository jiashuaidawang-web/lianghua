// ============================================================================================
// 【Day 12 · 阅读入口】Likelihood —— 假说可信度枚举。
// --------------------------------------------------------------------------------------------
//   在整条链里的位置：Day 12 Hypothesis 的"把握程度"标尺。
//   建议阅读时机：读完 Hypothesis 后读它。
//   学完能回答：为什么可信度由 Strategy 规则判定，而不是 LLM 给信心值？
//
//   💡 为什么不由 LLM 给信心值？
//     LLM 的"80% 把握"是不可靠的数字幻觉——它没有真实概率基础。
//     这里的可信度由 Strategy 根据证据匹配度确定性判定：
//       - 证据直接命中（如 stderr 明确报 "Connection refused"）→ HIGH
//       - 证据间接指向（如超时但可能是网络也可能是脚本死循环）→ MEDIUM
//       - 证据模糊（如只拿到"失败"两字）→ LOW
//     这样可信度有可追溯的证据基础，不是拍脑袋。
//
//   ⬇ 下一步：看 Hypothesis（Likelihood 是它的一个字段）。
// ============================================================================================

/**
 * 假说可信度：Strategy 根据证据匹配度确定性判定。
 */
public enum Likelihood {

    /** 证据直接命中根因。 */
    HIGH,

    /** 证据间接指向根因。 */
    MEDIUM,

    /** 证据模糊，仅能猜测。 */
    LOW;
}
