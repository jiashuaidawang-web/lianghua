package com.quant.agent.domain.task;

// ============================================================================================
// 【Day 5 · 阅读入口】TaskType —— 7 种标准任务类型的「菜单」，PlannerNode 的 LLM 只能从这里选。
// --------------------------------------------------------------------------------------------
//   在整条链里的位置：Day 5 域模型的基石。PlannerNode 生成的每个 Task 的 type 必须是其中之一。
//   建议阅读时机：Day 5 最先读它（1 分钟，但理解它为什么存在要 5 分钟）。
//   学完能回答：
//     1. 为什么是「7 种」而不是无限？
//     2. 这 7 种是怎么选出来的？
//     3. 如果用户的需求不在 7 种里怎么办？
//
//   💡 为什么限制为 7 种？（核心设计决策）
//     LLM 是概率性模型，如果让它自由发明 Task 类型，它会：
//       - 幻觉出不存在的类型（如 BUY_STOCK、DELETE_DATA）
//       - 发明系统没有 handler 的类型 → 执行时找不到处理者
//     所以必须给 LLM 一个「菜单」，让它只能从菜单里选。
//
//   💡 7 种是怎么选出来的？
//     这 7 种覆盖了量化金融 Agent 最常用的「能力类别」：
//       ANALYSIS   → 分析（调 LLM 做推理）
//       DATA_FETCH → 取数（调 Tool 获取真实数据）
//       FILTER     → 筛选（Java 代码做过滤）
//       ALERT      → 告警（设置提醒规则）
//       REPORT     → 报告（生成分析总结）
//       EXECUTE    → 执行（风险操作，需人工确认）
//       NOTIFY     → 通知（发送消息给用户）
//
//     注意：这里是「能力类别」不是「具体函数」。
//       DATA_FETCH 一种类型，但通过不同 params 可以查价格/查基本面/查历史走势。
//       7 种 × N 种 params = 几十几百种组合。
//
//   💡 如果用户的需求不在 7 种里怎么办？
//     方案 1：扩展枚举（加第 8 种、第 9 种）—— 推荐，显式可控
//     方案 2：加一个 UNKNOWN 兜底类型 —— 返回「暂不支持」
//     方案 3：多个 Task 组合逼近（如 CHART 用 DATA_FETCH + REPORT 组合）
//
//   💡 为什么用枚举不用 String？
//     枚举 = 编译期检查 + 反序列化时自动校验。
//     LLM 返回 "BUY_STOCK" → 反序列化到 TaskType 枚举直接失败 → 进入重试/失败路径。
//     如果用 String → 需要手写 if/else 校验，容易遗漏。
//
//   ⬇ 下一步：看 Task.java（TaskType + params 组成的任务数据模型）。
// ============================================================================================

/**
 * 7 种标准任务类型。
 *
 * <p>PlannerNode 的 LLM 只能返回这 7 种类型之一，不能发明新类型。
 * 这是防幻觉的核心机制：LLM 返回非法类型 → 反序列化失败 → 重试/失败。
 */
public enum TaskType {

    // -------------------------------------------------------------------------
    // 认知类：需要 LLM 推理
    // -------------------------------------------------------------------------

    /**
     * 分析股票 —— 调 LLM 做投资分析推理。
     * <p>典型场景：分析某只股票的投资价值、风险评估、行业前景。
     * <p>实现方式：调 StructuredAnalysisService（Day 2 能力）→ 拿到 StockAnalysis DTO。
     */
    ANALYSIS,

    // -------------------------------------------------------------------------
    // 数据类：获取真实数据
    // -------------------------------------------------------------------------

    /**
     * 获取数据 —— 调 @Tool 获取真实行情/基本面数据。
     * <p>典型场景：查当前价格、查市盈率、查历史走势。
     * <p>实现方式：调 StockTools（Day 3 能力）→ 返回 JSON 数据。
     * <p>不同查询通过 params 区分（如 fields: ["price"] vs fields: ["pe", "pb"]）。
     */
    DATA_FETCH,

    // -------------------------------------------------------------------------
    // 处理类：Java 确定性逻辑
    // -------------------------------------------------------------------------

    /**
     * 筛选过滤 —— Java 代码对数据做筛选。
     * <p>典型场景：从 5000 只股票中筛出 PE<30 的、筛出某个行业的。
     * <p>实现方式：纯 Java 代码，不调 LLM。
     */
    FILTER,

    /**
     * 设置告警 —— Java 代码设置价格/指标提醒规则。
     * <p>典型场景：茅台涨到 2000 通知我、PE 超过 50 通知我。
     * <p>实现方式：纯 Java 代码，可能写数据库或内存队列。
     */
    ALERT,

    // -------------------------------------------------------------------------
    // 输出类：生成结果
    // -------------------------------------------------------------------------

    /**
     * 生成报告 —— 汇总分析结果 + 数据，生成可读的报告文本。
     * <p>典型场景：生成一份「茅台投资分析报告」。
     * <p>实现方式：可能调 LLM 润色，也可能纯模板拼接。
     */
    REPORT,

    // -------------------------------------------------------------------------
    // 执行类：风险操作
    // -------------------------------------------------------------------------

    /**
     * 执行操作 —— 执行有副作用的操作（如下单、调仓）。
     * <p>典型场景：买入 100 股茅台、卖出某只股票。
     * <p>⚠ 高风险操作：必须经过 HITL（Human-in-the-Loop）人工确认后才能执行。
     * <p>实现方式：先写 State 标记「待确认」，等用户确认后再真正执行。
     */
    EXECUTE,

    /**
     * 通知用户 —— 发送消息通知。
     * <p>典型场景：分析完成通知、告警触发通知、日报推送。
     * <p>实现方式：写通知队列 / 调通知服务。
     */
    NOTIFY,

    // -------------------------------------------------------------------------
    // Day 11：沙盒执行类 —— LLM 生成的代码放进隔离容器安全执行
    // -------------------------------------------------------------------------

    /**
     * 沙盒执行 —— 在 Docker 隔离容器中安全执行 LLM 生成的脚本（如 Python 因子计算）。
     * <p>典型场景：LLM 生成一段计算 PE 分位数的 Python 代码，放进沙盒跑。
     * <p>实现方式：SandboxService → 策略校验(SandboxPolicy) → DockerSandboxExecutor。
     * <p>脚本来自 LLM（不可信输入），必须先过策略校验，再起容器。
     * <p>params 约定：script(必填) / language(默认 python) / inputData(可选) / limits(可选配额)。
     */
    SANDBOX;
}
