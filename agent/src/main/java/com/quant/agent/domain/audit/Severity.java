// 【Day 10 · 阅读入口】Severity —— 缺口严重级别枚举，DiffAuditNode 的风险分级依据。
// --------------------------------------------------------------------------------------------
//   在整条链里的位置：Day 10 缺口矩阵的"风险标尺"。
//   学完能回答：
//     1. 为什么分 4 级而不是"有/无"二值？
//     2. CRITICAL 和 HIGH 的边界在哪？
//     3. severity 由谁决定——LLM 还是 Java 规则？
//
//   💡 为什么分 4 级？
//     二值（有缺口/无缺口）太粗糙：
//       - "缺一个资金流向工具"和"缺所有数据工具"是不同的事
//       - 需要区分"完全做不到"和"有替代方案"
//     4 级让下游能按级别采取不同策略（见 DiffAuditNode）。
//
//   💡 CRITICAL vs HIGH 边界：
//     CRITICAL = 完全没能力 + 不可替代（如：需要交易执行，但没有任何交易接口）
//     HIGH     = 没直接能力 + 有近似替代（如：需要资金流向，但可用量价推断）
//
//   💡 severity 谁决定？
//     Java 规则决定（见 CapabilityInventory + DiffAuditService）。
//     这是 constitution 的"确定性审计"要求：不能靠 LLM 猜"严重不严重"。
//
//   ⬇ 下一步：看 GapItem（severity 是它的一个字段）。
// ============================================================================================

/**
 * 缺口严重级别。
 *
 * <p>由 Java 规则确定性判定，不由 LLM 评估。
 */
public enum Severity {

    /**
     * 严重：完全没能力，且不可替代。
     * <p>例：需要下单交易，但系统没有任何交易接口。
     * <p>策略：阻断执行，必须告知用户。
     */
    CRITICAL,

    /**
     * 高：没直接能力，但有近似替代。
     * <p>例：需要资金流向数据，但可用成交量+价格变动近似推断。
     * <p>策略：可继续执行，但需在 Gap Matrix 中标注替代方案。
     */
    HIGH,

    /**
     * 中：有能力但护栏可能拦截（限流/权限/MCP 远端不可用）。
     * <p>策略：可继续执行，标注风险。
     */
    MEDIUM,

    /**
     * 低：有能力但非最优（如用基本面替代资金流向）。
     * <p>策略：继续执行，仅记录。
     */
    LOW;
}
